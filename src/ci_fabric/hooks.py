"""Git hook installation with chaining of pre-existing hooks."""

from __future__ import annotations

import contextlib
import json
import shlex
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from . import __version__
from .context import Context
from .errors import CiError
from .pipeline import run_pipeline
from .report import finalize
from .util import (
    ensure_dir,
    git_output,
    isoformat,
    read_text,
    relpath,
    remove_path,
    run_git,
    utc_now,
    write_json,
)

HOOK_NAMES = ("pre-commit", "pre-push")
_STATE_NAME = "hooks-state.json"
_DISPATCHER = """#!/bin/sh
# Generated by ci-fabric. Do not edit; re-run `./ci hooks install`.
set -u
HOOK={hook}
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
PREVIOUS={previous}
if [ -n "$PREVIOUS" ] && [ -x "$PREVIOUS/$HOOK" ]; then
  "$PREVIOUS/$HOOK" "$@" || exit $?
fi
exec "$ROOT/ci" hook-run "$HOOK" "$@"
"""


@dataclass(slots=True)
class HookState:
    installed: bool
    hooks_path: str | None
    previous_hooks_path: str | None
    previous_was_default: bool
    hooks: list[str]

    def to_dict(self) -> dict[str, Any]:
        return {
            "installed": self.installed,
            "hooks_path": self.hooks_path,
            "previous_hooks_path": self.previous_hooks_path,
            "previous_was_default": self.previous_was_default,
            "hooks": self.hooks,
        }


def _hooks_root(root: Path) -> Path:
    return root / ".localci" / "githooks"


def _state_path(root: Path) -> Path:
    return root / ".localci" / _STATE_NAME


def _git_config_hooks_path(root: Path) -> tuple[str | None, Path | None]:
    value = git_output(root, ["config", "--local", "--get", "core.hooksPath"])
    if not value:
        return None, None
    candidate = Path(value)
    if not candidate.is_absolute():
        candidate = (root / candidate).resolve()
    return value, candidate


def _default_hooks_dir(root: Path) -> Path:
    value = git_output(root, ["rev-parse", "--git-path", "hooks"])
    candidate = Path(value) if value else Path(".git/hooks")
    if not candidate.is_absolute():
        candidate = (root / candidate).resolve()
    return candidate


def _read_state(root: Path) -> dict[str, Any] | None:
    path = _state_path(root)
    if not path.is_file():
        return None
    try:
        data = json.loads(read_text(path))
    except (CiError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def _previous_dir(root: Path, state: dict[str, Any] | None) -> tuple[Path | None, bool]:
    """Return the directory to chain and whether it is Git's default hooks dir."""
    ours = _hooks_root(root).resolve()
    configured, configured_path = _git_config_hooks_path(root)
    if configured_path is not None and configured_path != ours:
        return configured_path, False
    if configured is not None and configured_path == ours and state is not None:
        previous = state.get("previous_hooks_path")
        if isinstance(previous, str) and previous:
            return Path(previous), bool(state.get("previous_was_default"))
        if state.get("previous_was_default"):
            return _default_hooks_dir(root), True
        return None, False
    default = _default_hooks_dir(root)
    return default, True


def install_hooks(root: Path, *, force: bool = False) -> HookState:
    state = _read_state(root)
    _configured, configured_path = _git_config_hooks_path(root)
    hooks_dir = _hooks_root(root)
    if configured_path == hooks_dir.resolve() and all(
        (hooks_dir / name).is_file() for name in HOOK_NAMES
    ):
        return HookState(
            installed=True,
            hooks_path=relpath(hooks_dir, root),
            previous_hooks_path=(
                str(state.get("previous_hooks_path"))
                if state and state.get("previous_hooks_path")
                else None
            ),
            previous_was_default=bool(state.get("previous_was_default")) if state else False,
            hooks=[name for name in HOOK_NAMES if (hooks_dir / name).is_file()],
        )
    previous, was_default = _previous_dir(root, state)
    if previous is not None and previous.resolve() == _hooks_root(root).resolve():
        previous = None
    ensure_dir(hooks_dir)
    chained: list[str] = []
    for hook_name in HOOK_NAMES:
        previous_hook = (previous / hook_name) if previous is not None else None
        chain = (
            previous_hook is not None
            and previous_hook.is_file()
            and bool(previous_hook.stat().st_mode & 0o111)
        )
        if chain:
            chained.append(hook_name)
        content = _DISPATCHER.format(
            hook=shlex.quote(hook_name),
            previous=shlex.quote(str(previous)) if previous is not None else '""',
        )
        path = hooks_dir / hook_name
        path.write_text(content, encoding="utf-8", newline="\n")
        path.chmod(0o755)
    del force
    result = run_git(root, ["config", "--local", "core.hooksPath", relpath(hooks_dir, root)])
    if result.returncode != 0:
        raise CiError("could not set core.hooksPath: " + (result.stderr or result.stdout).strip())
    state_payload = {
        "schema_version": 1,
        "installed_at": isoformat(utc_now()),
        "tool_version": __version__,
        "previous_hooks_path": str(previous) if previous is not None else None,
        "previous_was_default": was_default,
        "chained_hooks": chained,
        "hooks": list(HOOK_NAMES),
        "mode": 0o755,
    }
    write_json(_state_path(root), state_payload)
    return HookState(
        installed=True,
        hooks_path=relpath(hooks_dir, root),
        previous_hooks_path=str(previous) if previous is not None else None,
        previous_was_default=was_default,
        hooks=chained,
    )


def uninstall_hooks(root: Path, *, force: bool = False) -> HookState:
    state = _read_state(root)
    configured, configured_path = _git_config_hooks_path(root)
    ours = _hooks_root(root).resolve()
    if configured_path != ours:
        if not force:
            return HookState(
                installed=False,
                hooks_path=configured,
                previous_hooks_path=(str(state.get("previous_hooks_path")) if state else None),
                previous_was_default=bool(state.get("previous_was_default")) if state else False,
                hooks=[],
            )
        # Never alter a hooksPath this tool does not own, even with --force.
        with contextlib.suppress(OSError):
            remove_path(_hooks_root(root))
        with contextlib.suppress(OSError):
            remove_path(_state_path(root))
        return HookState(
            installed=False,
            hooks_path=configured,
            previous_hooks_path=None,
            previous_was_default=False,
            hooks=[],
        )
    if state is not None:
        previous = state.get("previous_hooks_path")
        was_default = bool(state.get("previous_was_default"))
        if was_default or not isinstance(previous, str) or not previous:
            run_git(root, ["config", "--local", "--unset", "core.hooksPath"])
        else:
            run_git(root, ["config", "--local", "core.hooksPath", previous])
    else:
        run_git(root, ["config", "--local", "--unset", "core.hooksPath"])
    with contextlib.suppress(OSError):
        remove_path(_hooks_root(root))
    with contextlib.suppress(OSError):
        remove_path(_state_path(root))
    return HookState(
        installed=False,
        hooks_path=None,
        previous_hooks_path=None,
        previous_was_default=False,
        hooks=[],
    )


def hook_status(root: Path) -> HookState:
    configured, configured_path = _git_config_hooks_path(root)
    ours = _hooks_root(root).resolve()
    state = _read_state(root)
    installed = configured_path == ours
    return HookState(
        installed=installed,
        hooks_path=configured,
        previous_hooks_path=(
            str(state.get("previous_hooks_path"))
            if state and state.get("previous_hooks_path")
            else None
        ),
        previous_was_default=bool(state.get("previous_was_default")) if state else False,
        hooks=[name for name in HOOK_NAMES if (ours / name).is_file()] if installed else [],
    )


def run_hook(context: Context, hook_name: str, *, echo: Any = print) -> int:
    if hook_name not in HOOK_NAMES:
        raise CiError(
            f"unsupported hook: {hook_name}",
            remediation=f"Supported hooks: {', '.join(HOOK_NAMES)}.",
        )
    stages = (
        context.config.hooks.pre_commit_stages
        if hook_name == "pre-commit"
        else context.config.hooks.pre_push_stages
    )
    if not stages:
        echo(f"ci-fabric: {hook_name} has no configured stages")
        return 0
    result = run_pipeline(
        context,
        command=f"hook:{hook_name}",
        stages=stages,
        echo=echo,
    )
    finalize(
        context,
        command=result.command,
        stages=result.stages,
        status=result.status,
        exit_code=result.exit_code,
        started_at=result.started_at,
        release=result.release,
        error=result.error,
        metadata={"hook": hook_name, **result.metadata},
        echo=echo,
    )
    return result.exit_code
