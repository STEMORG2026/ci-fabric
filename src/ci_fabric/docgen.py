"""Generate ``docs/reference.md`` from the live code.

The reference is derived — never hand-edited — from the modules that define
the product: the command tables (:mod:`ci_fabric.commands`), the canonical
stage order (:mod:`ci_fabric.pipeline`), the exit-code contract
(:mod:`ci_fabric.errors`), the profile requirements (:mod:`ci_fabric.config`)
and the render placeholders (:class:`ci_fabric.context.Context`).

The pipeline enforces freshness through ``[repository].generated_checks``:
the gate regenerates this file on every run and fails when the committed
copy drifts, so documentation rot is a build failure, not a review comment.
"""

from __future__ import annotations

from . import __version__
from .commands import (
    AUX_COMMAND_HELP,
    DEPLOY_COMMAND_HELP,
    PIPELINE_COMMAND_HELP,
    RELEASE_STAGES,
    RUN_STAGES,
)
from .config import PROFILE_REQUIRED_STAGES, PROFILES, Config
from .context import Context
from .errors import (
    EXIT_CONFIG,
    EXIT_GATE_FAILED,
    EXIT_INTERRUPTED,
    EXIT_OK,
    EXIT_PREREQUISITE,
)
from .pipeline import CANONICAL_ORDER, COMMAND_STAGES

REFERENCE_RELATIVE_PATH = "docs/reference.md"

GENERATED_MARKER = "<!-- GENERATED by `./ci docs`; do not edit this file by hand. -->"


def _command_stages(name: str) -> str:
    if name == "run":
        return RUN_STAGES
    if name == "release":
        return RELEASE_STAGES
    stages = COMMAND_STAGES.get(name)
    if not stages:
        return "—"
    return ", ".join(stages)


def generate_reference(config: Config, context: Context) -> str:
    """Render the reference document for this version of the tool."""
    lines: list[str] = []
    add = lines.append

    add(GENERATED_MARKER)
    add("")
    add(f"# Reference — commands, stages, exit codes (ci-fabric {__version__})")
    add("")
    add("Generated from the live code by `./ci docs`. If this file and the")
    add("source disagree, the source wins: regenerate and commit. The")
    add("`repository.generated` gate fails the pipeline whenever this file")
    add("drifts, so it cannot silently rot.")
    add("")

    add("## Exit codes")
    add("")
    add("| code | meaning |")
    add("| --- | --- |")
    add(f"| `{EXIT_OK}` | success |")
    add(f"| `{EXIT_GATE_FAILED}` | a blocking gate failed |")
    add(f"| `{EXIT_CONFIG}` | configuration or usage error |")
    add(f"| `{EXIT_PREREQUISITE}` | a required prerequisite is unavailable |")
    add(f"| `{EXIT_INTERRUPTED}` | interrupted by the user |")
    add("")

    add("## Pipeline stages (canonical order)")
    add("")
    add(" → ".join(f"`{name}`" for name in CANONICAL_ORDER))
    add("")
    add("Packaging runs before artifact validation on purpose: the artifact")
    add("gates verify the exact bytes that would be released or deployed.")
    add("")

    add("## Pipeline commands")
    add("")
    add("| command | purpose | stages |")
    add("| --- | --- | --- |")
    for name, help_text in PIPELINE_COMMAND_HELP:
        add(f"| `./ci {name}` | {help_text} | {_command_stages(name)} |")
    add("| `./ci run` | explicit stage selection | " + RUN_STAGES + " |")
    add("| `./ci release` | full pipeline plus a verified local release | " + RELEASE_STAGES + " |")
    add("")

    add("## Deployment commands")
    add("")
    add("| command | purpose |")
    add("| --- | --- |")
    for name, help_text in DEPLOY_COMMAND_HELP:
        add(f"| `./ci {name}` | {help_text} |")
    add("")

    add("## Utility commands")
    add("")
    add("| command | purpose |")
    add("| --- | --- |")
    for name, help_text in AUX_COMMAND_HELP:
        add(f"| `./ci {name}` | {help_text} |")
    add("")

    add("## Profiles")
    add("")
    add("| profile | required stages |")
    add("| --- | --- |")
    for profile in PROFILES:
        required = ", ".join(f"`{s}`" for s in sorted(PROFILE_REQUIRED_STAGES[profile]))
        add(f"| `{profile}` | {required} |")
    add("")
    add("Required stages are BLOCKING wherever they are configured; the")
    add("`[policy].required_stages` list extends the profile's set.")
    add("")

    add("## Placeholders")
    add("")
    add("Available in commands and path-valued configuration keys:")
    add("")
    placeholders = sorted(context._placeholders())
    add(", ".join(f"`{{{name}}}`" for name in placeholders))
    add("")
    add("`${NAME}` expands stage/deploy environment variables instead; a")
    add("missing variable is a hard error, never an empty string.")
    add("")

    return "\n".join(lines)
